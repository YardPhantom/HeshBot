#!/usr/bin/env python3
"""Regenerate api/knowledge.md from the public pages of trevorheshka.com.

Usage: python3 tools/build_knowledge.py /path/to/site-root
Only the standard library is used. Pages and lines mentioning excluded
terms are dropped so they never reach the model.
"""
import html, os, re, sys
from html.parser import HTMLParser

PAGES = [("Homepage", "index.html"), ("About", "about/index.html"),
         ("AI", "ai/index.html"), ("Projects", "projects/index.html"),
         ("IT Support Nanaimo", "it-support-nanaimo/index.html"),
         ("Full-Stack Nanaimo", "full-stack-nanaimo/index.html")]
EXCLUDE = re.compile(r"instagram[-_ ]?auto[-_ ]?darkroom|auto[-_ ]?darkroom", re.I)
SKIP_TAGS = {"script", "style", "noscript", "svg", "template", "head"}
BLOCK = {"p", "div", "li", "h1", "h2", "h3", "h4", "h5", "h6", "section", "article",
         "br", "tr", "dt", "dd", "header", "footer", "nav", "main", "ul", "ol", "blockquote"}

class Text(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out, self.skip, self.title, self.desc, self._t = [], 0, "", "", False
    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "title": self._t = True
        if tag == "meta" and a.get("name") == "description": self.desc = a.get("content", "")
        if tag in SKIP_TAGS: self.skip += 1
        if tag in BLOCK: self.out.append("\n")
        if tag in ("h1", "h2", "h3") and not self.skip: self.out.append("### ")
        if tag == "li" and not self.skip: self.out.append("- ")
    def handle_endtag(self, tag):
        if tag == "title": self._t = False
        if tag in SKIP_TAGS and self.skip: self.skip -= 1
        if tag in BLOCK: self.out.append("\n")
    def handle_data(self, d):
        if self._t: self.title += d
        elif not self.skip: self.out.append(d)

def extract(path):
    p = Text(); p.feed(open(path, encoding="utf-8", errors="ignore").read())
    lines, seen = [], set()
    for ln in "".join(p.out).split("\n"):
        ln = re.sub(r"\s+", " ", ln).strip()
        if len(ln) < 3 or ln in ("###", "-") or EXCLUDE.search(ln) or ln in seen: continue
        seen.add(ln); lines.append(ln)
    return p.title.strip(), p.desc.strip(), "\n".join(lines)

def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "../site/trevorheshka-edit"
    pages = list(PAGES)
    pdir = os.path.join(root, "projects")
    if os.path.isdir(pdir):
        for d in sorted(os.listdir(pdir)):
            f = os.path.join("projects", d, "index.html")
            if os.path.isfile(os.path.join(root, f)) and not EXCLUDE.search(d):
                pages.append(("Project: " + d, f))
    out = ["# Knowledge base for HeshBot (generated by tools/build_knowledge.py; do not edit by hand)\n"]
    for label, rel in pages:
        fp = os.path.join(root, rel)
        if not os.path.isfile(fp): print("skip (missing):", rel, file=sys.stderr); continue
        title, desc, body = extract(fp)
        url = "https://trevorheshka.com/" + rel.replace("index.html", "")
        out.append("\n## %s (%s)\n" % (label, url))
        if title: out.append("Title: %s\n" % title)
        if desc and not EXCLUDE.search(desc): out.append("Summary: %s\n" % desc)
        out.append(body[:12000] + "\n")
    dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "api", "knowledge.md")
    text = "".join(out)
    assert not EXCLUDE.search(text)
    open(dest, "w", encoding="utf-8").write(text)
    print("wrote %s (%d chars)" % (os.path.normpath(dest), len(text)))

if __name__ == "__main__": main()
